#!/usr/bin/env node
/**
 * Writes the third-party notices of a shipped web bundle: every package of its production
 * dependency tree (scripts/frontend-deps.mjs, the walk the licence guard does) with its version,
 * its licence and the licence / notice files the package itself ships.
 *
 * Why: MIT, BSD and Apache-2.0 §4 all require the copyright and permission notice to travel with
 * every copy. A minified bundle keeps none of them, so the notices go next to it as a file:
 * THIRD-PARTY-LICENSES.txt in dist/assets — which is what the io.mateu:mateu-vaadin jar, the
 * mateu-vaadin npm package and the static sites ship, and (visual-editor) what the IDE plugins embed.
 *
 * Usage (from anywhere; the bundle's workspaces must be installed, `npm ci`):
 *   node scripts/third-party-notices.mjs <bundle> --out <file>     write it
 *   node scripts/third-party-notices.mjs <bundle> --check <file>   fail when <file> is not current
 * Bundles: vaadin, visual-editor (BUNDLES in frontend-deps.mjs). The output is deterministic (sorted,
 * no dates), so the committed copy can be checked against a fresh one in CI.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { BUNDLES, licenceOf, walk } from './frontend-deps.mjs'

const LEGAL_FILE = /^(licen[cs]e|copying|notice|authors)([.-].*)?$/i

const legalFilesOf = (dir) =>
  readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && LEGAL_FILE.test(e.name))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b))

const RULE = '-'.repeat(78)

export const notices = (bundle) => {
  const target = BUNDLES[bundle]
  if (!target) throw new Error(`Unknown bundle ${bundle} — known: ${Object.keys(BUNDLES).join(', ')}`)
  const { packages, unresolved } = walk(target)
  if (unresolved.length) {
    throw new Error(`${unresolved.length} dependency(ies) not installed — run \`npm ci\` in ${target.dir} first:\n  ${unresolved.join('\n  ')}`)
  }
  const out = [
    `Third-party software in the Mateu ${bundle} web bundle`,
    '',
    'This bundle is Mateu code (Apache License 2.0, see LICENSE.txt and NOTICE in the Mateu',
    'distribution) compiled together with the open-source packages listed below. Each package',
    'is distributed under its own licence; its copyright and licence notices follow, as the',
    'package publishes them. Generated by scripts/third-party-notices.mjs from the production',
    'dependency tree — do not edit by hand.',
    '',
    `${packages.length} packages:`,
    '',
    ...packages.map(({ pkg }) => `  ${pkg.name}@${pkg.version}  (${licenceOf(pkg)})`),
    '',
  ]
  // the same licence text (the Apache-2.0 LICENSE of every Vaadin package) is given once, and
  // referred to after that
  const firstWith = new Map()
  for (const { pkg, dir } of packages) {
    out.push(RULE, `${pkg.name}@${pkg.version}`, `Licence: ${licenceOf(pkg)}`)
    const home = pkg.homepage ?? (typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url)
    if (home) out.push(`Source: ${home}`)
    const files = legalFilesOf(dir)
    if (!files.length) {
      out.push('', `(The package ships no licence file; its package.json declares ${licenceOf(pkg)}${pkg.author ? `, author ${typeof pkg.author === 'string' ? pkg.author : pkg.author.name}` : ''}.)`)
    }
    for (const file of files) {
      const text = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trimEnd()
      const first = firstWith.get(text)
      if (first) {
        out.push('', `--- ${file}: the same text as ${first} above`)
      } else {
        firstWith.set(text, `${pkg.name}@${pkg.version}'s ${file}`)
        out.push('', `--- ${file}`, '', text)
      }
    }
    out.push('')
  }
  return out.join('\n') + '\n'
}

const main = (argv) => {
  const [bundle, flag, file] = argv
  if (!bundle || !['--out', '--check'].includes(flag) || !file) {
    console.error('Usage: node scripts/third-party-notices.mjs <bundle> --out|--check <file>')
    return 2
  }
  let text
  try {
    text = notices(bundle)
  } catch (e) {
    console.error(`✗ ${e.message}`)
    return 2
  }
  if (flag === '--out') {
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, text)
    console.log(`✓ ${file}`)
    return 0
  }
  if (existsSync(file) && readFileSync(file, 'utf8') === text) {
    console.log(`✓ ${file} lists the ${bundle} bundle's current dependencies`)
    return 0
  }
  console.error(`✗ ${file} is not the notices of the current ${bundle} dependency tree.`)
  console.error(`  Regenerate it with the bundle (npm run copy in its app), or: node scripts/third-party-notices.mjs ${bundle} --out ${file}`)
  return 1
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main(process.argv.slice(2)))
