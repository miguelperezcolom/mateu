package com.example.demo;

import static org.springframework.boot.test.context.SpringBootTest.WebEnvironment.RANDOM_PORT;

import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webtestclient.autoconfigure.AutoConfigureWebTestClient;
import org.springframework.http.MediaType;
import org.springframework.test.web.reactive.server.WebTestClient;

/**
 * Boots the real application and exercises mateu over HTTP, to prove that spring boot webflux
 * needs no special setup: every mateu bean comes from the io.mateu:mateu-webflux jar and the
 * controllers are generated by the annotation processor, with a plain javac compile.
 */
@SpringBootTest(webEnvironment = RANDOM_PORT)
@AutoConfigureWebTestClient
class MateuHttpE2eTest {

  @Autowired WebTestClient webTestClient;

  @Test
  void indexIsServedForUiRoute() {
    webTestClient
        .get()
        .uri("/counter")
        .exchange()
        .expectStatus()
        .isOk()
        .expectBody(String.class)
        .value(body -> org.assertj.core.api.Assertions.assertThat(body).contains("<mateu-ui baseUrl=\"/counter\""));
  }

  @Test
  void spaSubRouteServesTheSameIndex() {
    webTestClient
        .get()
        .uri("/counter/section1")
        .exchange()
        .expectStatus()
        .isOk()
        .expectBody(String.class)
        .value(body -> org.assertj.core.api.Assertions.assertThat(body).contains("<mateu-ui baseUrl=\"/counter\""));
  }

  @Test
  void initialLoadReturnsTheComponentTree() {
    webTestClient
        .post()
        .uri("/counter/mateu/v3/x")
        .contentType(MediaType.APPLICATION_JSON)
        .bodyValue(runActionPayload(""))
        .exchange()
        .expectStatus()
        .isOk()
        .expectBody(String.class)
        .value(
            body ->
                org.assertj.core.api.Assertions.assertThat(body)
                    .contains("\"serverSideType\":\"com.example.demo.Counter\"")
                    .contains("\"label\":\"Increment\""));
  }

  @Test
  void theCounterAdvertisesItsLambdaButton() {
    // the web client only SENDS an action the component advertises: the Increment button's
    // handler is a lambda, no action method backs it, and it went unadvertised in production
    // (3.0-alpha.411) — the click was dropped in the browser although the server would run it
    webTestClient
        .post()
        .uri("/counter/mateu/v3/x")
        .contentType(MediaType.APPLICATION_JSON)
        .bodyValue(runActionPayload(""))
        .exchange()
        .expectStatus()
        .isOk()
        .expectBody(String.class)
        .value(
            body ->
                org.assertj.core.api.Assertions.assertThat(body)
                    .containsPattern("\"actions\":\\[\\{\"id\":\"increment\""));
  }

  @Test
  void theRootServesTheWelcomePage() {
    webTestClient
        .get()
        .uri("/")
        .exchange()
        .expectStatus()
        .isOk()
        .expectBody(String.class)
        .value(
            body ->
                org.assertj.core.api.Assertions.assertThat(body)
                    .contains("<mateu-ui baseUrl=\"\""));
    webTestClient
        .post()
        .uri("/mateu/v3/sync/_no_route")
        .contentType(MediaType.APPLICATION_JSON)
        .bodyValue(
            Map.of(
                "componentState", Map.of(),
                "appState", Map.of(),
                "parameters", Map.of(),
                "actionId", "",
                "route", ""))
        .exchange()
        .expectStatus()
        .isOk()
        .expectBody(String.class)
        .value(
            body ->
                org.assertj.core.api.Assertions.assertThat(body)
                    .contains("\"serverSideType\":\"com.example.demo.Home\"")
                    .contains("Mateu demos")
                    .contains("\"url\":\"/counter\""));
  }

  @Test
  void runActionExecutesTheActionAndReturnsTheNewState() {
    webTestClient
        .post()
        .uri("/counter/mateu/v3/x")
        .contentType(MediaType.APPLICATION_JSON)
        .bodyValue(runActionPayload("increment"))
        .exchange()
        .expectStatus()
        .isOk()
        .expectBody(String.class)
        .value(body -> org.assertj.core.api.Assertions.assertThat(body).contains("\"count\":1"));
  }

  private static Map<String, Object> runActionPayload(String actionId) {
    return Map.of(
        "componentState", Map.of(),
        "appState", Map.of(),
        "parameters", Map.of(),
        "actionId", actionId,
        "route", "/counter",
        "serverSideType", "com.example.demo.Counter");
  }
}
