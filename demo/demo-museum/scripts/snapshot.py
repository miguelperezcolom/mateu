#!/usr/bin/env python3
"""
Writes the parts of demo-museum that a YAML component has to CARRY rather than fetch.

A Mateu Listing reads its rows from a REST source, but a Chart, a Kanban and a Calendar carry their
data in the definition — there is no `source:` on them — and a MetricCard does not interpolate
${state…} on Vaadin. So for those this script reads museum-service once and writes the YAML:

  specs/ui/partials/generated/dashboard-kpis.yaml     the dashboard's scoreboard   (/api/stats)
  specs/ui/partials/generated/dashboard-charts.yaml   the dashboard's chart panels (/api/stats)
  specs/ui/calendar.yaml                              the exhibition calendar (/api/exhibitions)

Each card and each event opens the live record (conservation/tasks/:id, exhibitions/:id), so the
snapshot is only the overview: what you open and edit is always the API's current state. Re-run it
after the seed changes:

    python3 scripts/snapshot.py                       # museum-service on http://localhost:8121
    python3 scripts/snapshot.py https://museum.example.org
"""
import json
import sys
import urllib.request
from pathlib import Path

BASE = (sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8121").rstrip("/")
UI = Path(__file__).resolve().parent.parent / "src" / "main" / "resources" / "specs" / "ui"
HEADER = "# GENERATED by scripts/snapshot.py from museum-service ({what}) — do not edit; re-run the script.\n"


def get(path):
    with urllib.request.urlopen(BASE + path, timeout=30) as r:
        return json.loads(r.read().decode())


def q(text):
    """A YAML double-quoted scalar."""
    return json.dumps("" if text is None else str(text), ensure_ascii=False)


MUSEUM_COLOURS = {"MET": "#c8102e", "SMK": "#1d4ed8", "CMA": "#047857"}
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def dashboard_charts():
    s = get("/api/stats")
    months = [m["month"] for m in s["visitsByMonth"]]
    labels = [MONTHS[int(m[5:7]) - 1] for m in months]
    codes = [p["code"] for p in s["perMuseum"]]
    names = {p["code"]: p["name"] for p in s["perMuseum"]}
    out = [HEADER.format(what="/api/stats")]
    out.append("""# The dashboard's panels: a hero chart across the full width, then four panels read together.
content:
- type: DashboardPanel
  title: Visitors per month
  subtitle: Every open day of 2026, by museum
  colSpan: 2
  content:
    type: Chart
    chartType: line
    chartData:
      labels: [%s]
      datasets:
""" % ", ".join(labels))
    for code in codes:
        data = [m["visitorsByMuseum"].get(code, 0) for m in s["visitsByMonth"]]
        out.append(f"        - {{label: {q(names[code])}, data: [{', '.join(map(str, data))}], borderColor: {q(MUSEUM_COLOURS.get(code))}, backgroundColor: {q(MUSEUM_COLOURS.get(code))}}}\n")
    kinds = sorted(s["artworksByClassification"].items(), key=lambda kv: -kv[1])
    top, rest = kinds[:7], sum(v for _, v in kinds[7:])
    labels = [k for k, _ in top] + (["Other kinds"] if rest else [])
    values = [v for _, v in top] + ([rest] if rest else [])
    out.append(f"""- type: DashboardPanel
  title: The collection by kind
  subtitle: {s['artworks']} public-domain works
  content:
    type: Chart
    chartType: doughnut
    chartData:
      labels: [{', '.join(q(l) for l in labels)}]
      datasets:
        - {{label: Works, data: [{', '.join(map(str, values))}]}}
- type: DashboardPanel
  title: Works per museum
  subtitle: Held, and on view today
  content:
    type: Chart
    chartType: bar
    chartData:
      labels: [{', '.join(q(p['name']) for p in s['perMuseum'])}]
      datasets:
        - {{label: Held, data: [{', '.join(str(p['artworks']) for p in s['perMuseum'])}]}}
        - {{label: On view, data: [{', '.join(str(p['onView']) for p in s['perMuseum'])}]}}
""")
    flow = ["requested", "approved", "in_transit", "on_display", "returned"]
    out.append(f"""- type: DashboardPanel
  title: Loans by stage
  subtitle: From request to return
  content:
    type: Chart
    chartType: bar
    chartData:
      labels: [Requested, Approved, In transit, On display, Returned]
      datasets:
        - {{label: Loans, data: [{', '.join(str(s['loansByStatus'].get(k, 0)) for k in flow)}]}}
""")
    board = ["backlog", "in_progress", "review", "done"]
    out.append(f"""- type: DashboardPanel
  title: Conservation
  subtitle: Tasks on the boards
  content:
    type: Chart
    chartType: pie
    chartData:
      labels: [Backlog, In progress, Review, Done]
      datasets:
        - {{label: Tasks, data: [{', '.join(str(s['tasksByStatus'].get(k, 0)) for k in board)}]}}
""")
    path = UI / "partials" / "generated" / "dashboard-charts.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))
    print("wrote", path.relative_to(UI.parent.parent.parent.parent.parent))


def dashboard_kpis():
    s = get("/api/stats")
    out = [HEADER.format(what="/api/stats")]
    out.append("content:\n")
    out.append(f"""- {{type: MetricCard, title: Visitors, value: {q(s['visitorsYtdLabel'])}, timeframe: 2026 to date, icon: "vaadin:users"}}
- {{type: MetricCard, title: Ticket revenue, value: {q(s['revenueYtdLabel'])}, timeframe: 2026 to date}}
- {{type: MetricCard, title: Artworks, value: {q(s['artworks'])}, description: {q(str(s['onView']) + ' on view')}}}
- {{type: MetricCard, title: Open exhibitions, value: {q(s['openExhibitions'])}, description: {q(str(s['plannedExhibitions']) + ' planned')}, actionId: open-exhibitions}}
- {{type: MetricCard, title: Active loans, value: {q(s['activeLoans'])}, description: {q('of ' + str(s['loans']))}, actionId: open-loans}}
- {{type: MetricCard, title: Open conservation tasks, value: {q(s['openTasks'])}, description: {q(str(s['urgentTasks']) + ' urgent')}, actionId: open-board}}
""")
    path = UI / "partials" / "generated" / "dashboard-kpis.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))
    print("wrote", path.name)


def conservation_board():
    tasks = get("/api/conservation-tasks?size=200&sort=dueDate")["content"]
    # colours are CSS colours: a card's tints its left border, a column's its header
    columns = [("backlog", "Backlog", "#6b7280"), ("in_progress", "In progress", "#2563eb"),
               ("review", "Review", "#d97706"), ("done", "Done", "#059669")]
    tone = {"urgent": "#dc2626", "high": "#d97706", "medium": "#2563eb", "low": "#9ca3af"}
    code = {"The Metropolitan Museum of Art": "Met", "Statens Museum for Kunst": "SMK",
            "Cleveland Museum of Art": "Cleveland"}
    out = [HEADER.format(what="/api/conservation-tasks")]
    out.append("""# The conservation board — a KANBAN: one column per status, one card per task, its colour the
# priority. A YAML Kanban carries its cards (it has no REST source), so this page is a snapshot; each
# card opens the LIVE task (conservation/tasks/:id), where moving it to another column is a status
# change saved to museum-service. The live, filterable list is conservation/tasks.
$schema: https://raw.githubusercontent.com/miguelperezcolom/mateu/master/backend/shared/uidl/specs-schema.json
type: Form
title: Conservation board
subtitle: Every task across the three museums — open a card to move it along
toolbar:
  - {type: Button, label: New task, buttonStyle: primary, actionable: {type: RouteLink, route: conservation/tasks/new}}
  - {type: Button, label: As a list, actionable: {type: RouteLink, route: conservation/tasks}}
content:
  - type: Kanban
    id: board
    columns:
""")
    for status, title, colour in columns:
        out.append(f"      - id: {status}\n        title: {title}\n        color: {q(colour)}\n        cards:\n")
        mine = [t for t in tasks if t["status"] == status]
        if not mine:
            out[-1] = out[-1].replace("cards:\n", "cards: []\n")
        for t in mine:
            desc = f"{t['artworkTitle'][:48]} · {code.get(t['museumName'], t['museumName'])} · {t['assignee']} · due {t['dueDate']}"
            out.append(f"          - {{id: {q('t' + str(t['id']))}, title: {q(t['type'])}, description: {q(desc)}, "
                       f"badge: {q(t['priority'])}, color: {q(tone.get(t['priority'], '#9ca3af'))}, actionId: open-task-{t['id']}}}\n")
    out.append("actions:\n")
    for t in tasks:
        out.append(f"  - {{id: open-task-{t['id']}, steps: [{{type: Navigate, route: conservation/tasks/{t['id']}}}]}}\n")
    (UI / "conservation.yaml").write_text("".join(out))
    print("wrote conservation.yaml:", len(tasks), "cards")


def exhibition_calendar():
    exhibitions = get("/api/exhibitions?size=200&sort=startDate")["content"]
    colour = {"planned": "#6b7280", "open": "#047857", "closed": "#9ca3af"}
    out = [HEADER.format(what="/api/exhibitions")]
    out.append("""# The exhibition calendar — a CALENDAR of every show, each a multi-day event from its opening to its
# closing, coloured by status; month, week and agenda views switch in place. A YAML Calendar carries
# its events (it has no REST source), so this page is a snapshot; each event opens the LIVE exhibition.
$schema: https://raw.githubusercontent.com/miguelperezcolom/mateu/master/backend/shared/uidl/specs-schema.json
type: Form
title: Exhibition calendar
subtitle: Planned (grey), open (green) and closed shows across the three museums
toolbar:
  - {type: Button, label: New exhibition, buttonStyle: primary, actionable: {type: RouteLink, route: exhibitions/new}}
  - {type: Button, label: As a list, actionable: {type: RouteLink, route: exhibitions}}
content:
  - type: Calendar
    id: exhibitions-calendar
    month: "2026-10-31"
    view: month
    views: [month, list]
    days:
      - {date: "2026-10-31", label: Today, tone: info}
    events:
""")
    for e in exhibitions:
        out.append(f"      - {{id: {q('e' + str(e['id']))}, title: {q(e['title'] + ' · ' + (e['museumName'] or ''))}, "
                   f"date: {q(e['startDate'])}, endDate: {q(e['endDate'])}, color: {q(colour.get(e['status']))}, "
                   f"actionId: open-exhibition-{e['id']}}}\n")
    out.append("actions:\n")
    for e in exhibitions:
        out.append(f"  - {{id: open-exhibition-{e['id']}, steps: [{{type: Navigate, route: exhibitions/{e['id']}}}]}}\n")
    (UI / "calendar.yaml").write_text("".join(out))
    print("wrote calendar.yaml:", len(exhibitions), "events")


if __name__ == "__main__":
    dashboard_kpis()
    dashboard_charts()
    # conservation_board() — the board is LIVE now (conservation.yaml reads museum-service itself)
    exhibition_calendar()
