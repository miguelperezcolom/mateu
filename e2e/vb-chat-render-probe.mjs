/**
 * Probe of the AI chat's UI events on the VB/Redwood renderer (apps/redwood poc/chat.mjs
 * dispatchChatEvent): a `render-screen` with YAML renders on a page that does NOT subscribe to it
 * (the built-in render target, through `__preview__`) and does so MID-STREAM, a page that DOES
 * subscribe (demo-vb's ChatGenerate, @SubscribeTo("render-screen")) gets it instead, drawer and
 * dialog targets, an invalid YAML shows the backend's red text, `navigation-requested` navigates and
 * `close-requested` closes the panel.
 *
 * It runs its OWN scripted agent (no model) on AGENT_PORT, and the browser's chat stream (the app's
 * @AI(sse = "/agent/stream")) is sent straight to it — streaming kept, so "mid-stream" is real.
 *   cd demo/demo-vb && java -jar target/demo-vb-0.0.1-SNAPSHOT.jar --server.port=21401
 *   cd frontend/web/monorepo/apps/redwood && npm run build && npx grunt vb-serve --port=21402
 *   cd e2e && VB_URL=http://localhost:21402/ VB_BACKEND=http://localhost:21401 node vb-chat-render-probe.mjs
 *
 * VB_BACKEND: when set, the app's development backend (the mateuBaseUrl constant,
 * http://localhost:9005) is rewritten to it in the browser — so the probe can run next to another
 * demo-vb on :9005. Exits non-zero if a check fails.
 */
import http from 'node:http'
import { chromium } from 'playwright'
import { gotoVbReady, waitForVbReady } from './vb-ready.mjs'

const VB_URL = process.env.VB_URL || 'http://localhost:9006/'
const VB_BACKEND = process.env.VB_BACKEND || ''
const DEV_BACKEND = 'http://localhost:9005'
const AGENT_PORT = Number(process.env.AGENT_PORT || 21403)
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const results = []
const check = (n, ok, d = '') => { results.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${d ? ` — ${d}` : ''}`) }

// ── the scripted agent: the message names the scenario ─────────────────────────────────────────
const GENERATED = 'Generated by the agent'
// the title IS the marker (a form with fields shows its fields, not loose texts)
const yamlOf = (title) => `type: Form\ntitle: ${title}\ncontent:\n  - {type: FormField, id: guest, label: Guest, dataType: string}\n`
const scenarios = {
  render: [{ event: 'render-screen', detail: { yaml: yamlOf(GENERATED) } }],
  drawer: [{ event: 'render-screen', detail: { yaml: yamlOf('In a drawer'), target: 'drawer', title: 'Generated drawer' } }],
  dialog: [{ event: 'render-screen', detail: { yaml: yamlOf('In a dialog'), target: 'dialog', title: 'Generated dialog' } }],
  bad: [{ event: 'render-screen', detail: { yaml: '::: [not yaml' } }],
  products: [{ event: 'navigation-requested', detail: { route: '/products' } }],
  hello: [{ event: 'navigation-requested', detail: { route: '/hello' } }],
  close: [{ event: 'close-requested' }],
}
const agent = http.createServer((req, res) => {
  let raw = ''
  req.on('data', (c) => { raw += c })
  req.on('end', async () => {
    let message = ''
    try { message = JSON.parse(raw || '{}').message || '' } catch { /* empty */ }
    const events = scenarios[String(message).trim()] || []
    res.writeHead(200, { 'content-type': 'text/event-stream', 'cache-control': 'no-cache', 'access-control-allow-origin': '*' })
    res.write('data: ' + JSON.stringify({ event: 'agent-status', detail: { phase: 'thinking', text: 'Working on it' } }) + '\n\n')
    for (const e of events) res.write('data: ' + JSON.stringify(e) + '\n\n')
    // the answer is still streaming for a while after the event: what it opened must already show
    await sleep(4000)
    res.write('data: ' + JSON.stringify({ inputTokens: 10, outputTokens: 20 }) + '\n\n')
    res.write('data: Here it is\n\n')
    res.end()
  })
})
await new Promise((r) => agent.listen(AGENT_PORT, r))

const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 } })
const page = await ctx.newPage()
if (VB_BACKEND) {
  await page.route(DEV_BACKEND + '/**', (route) => route.continue({ url: route.request().url().replace(DEV_BACKEND, VB_BACKEND) }))
}
// the chat stream goes to the scripted agent (the preflight of the cross-origin POST answered here)
await page.route('**/agent/stream', (route) => route.request().method() === 'OPTIONS'
  ? route.fulfill({ status: 204, headers: { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': 'POST' } })
  : route.continue({ url: `http://localhost:${AGENT_PORT}/agent/stream` }))
if (process.env.DEBUG) {
  page.on('console', (m) => { if (/mateu-chat|Error/i.test(m.text())) console.log('  console:', m.text().slice(0, 300)) })
  page.on('request', (r) => { if (r.method() === 'POST') console.log('  POST', r.url(), (r.postData() || '').slice(0, 900)) })
}
const previews = []
page.on('request', (r) => {
  if (r.method() === 'POST' && /\/mateu\/v3\/sync\//.test(r.url())) {
    if ((r.postData() || '').includes('"actionId":"__preview__"')) previews.push(r.url())
  }
})
// what the page shows OUTSIDE the chat panel (the panel lives inside the content layout)
const content = () => page.evaluate(() => {
  const clone = document.body.cloneNode(true)
  for (const el of clone.querySelectorAll('#mateuChatPanel')) el.remove()
  return clone.innerText || clone.textContent || ''
}).catch(() => '')
const chatText = () => page.locator('#mateuChatPanel').innerText().catch(() => '')
const chatOpen = async () => (await page.locator('#mateuChatPanel .mateu-chat-panel-header').count()) > 0
const openChat = async () => {
  if (await chatOpen()) return
  await page.locator('#mateuChatToggle').click()
  await page.waitForSelector('#mateuChatInput input', { timeout: 10000 })
}
const say = async (text) => {
  await openChat()
  const input = page.locator('#mateuChatInput input')
  await input.fill(text)
  // the Send button (Enter is wired a moment after the panel opens — too late for a fast probe)
  await page.locator('#mateuChatSend').click()
}
const waitFor = async (fn, timeout = 10000) => {
  const deadline = Date.now() + timeout
  while (Date.now() < deadline) { if (await fn()) return true; await sleep(150) }
  return false
}
const answered = async () => (await chatText()).includes('Here it is')
const answerCount = async () => (await chatText()).split('Here it is').length - 1
// a fresh app each time (a hash change alone would keep the chat and any open overlay)
const go = async (route, texts) => {
  await page.goto('about:blank')
  await gotoVbReady(page, VB_URL + '#' + route, { texts })
}
const loads = []
page.on('request', (r) => {
  const body = r.postData() || ''
  if (r.method() === 'POST' && /\/mateu\/v3\/sync\//.test(r.url()) && !body.includes('__preview__')) loads.push(r.url())
})

try {
  // 1) a page that does NOT subscribe: the built-in render target paints the YAML, mid-stream
  await go('/hello', ['Hola desde Mateu'])
  await say('render')
  const painted = await waitFor(async () => (await content()).includes(GENERATED), 3500)
  check('render-screen with YAML renders on a page with NO @SubscribeTo', painted)
  check('…and it renders MID-STREAM (before the answer finished)', painted && !(await answered()))
  check('…through the reserved __preview__ action', previews.length === 1, `${previews.length} preview call(s)`)
  await waitFor(answered, 8000)
  await page.screenshot({ path: '/tmp/vb-chat-render.png' })

  // 1b) transient: a click on the SAME menu entry shows the real screen again
  {
    const before = loads.length
    await page.locator('#mateuNavList').getByText('Hello', { exact: true }).first().click()
    check('a click on the same menu entry brings the real screen back',
      await waitFor(async () => loads.slice(before).some((u) => /\/sync\/hello$/.test(u)) && !(await content()).includes(GENERATED), 5000))
    await waitForVbReady(page, { timeout: 15000 })
    await say('render')
    await waitFor(async () => (await content()).includes(GENERATED), 5000)
    await waitFor(async () => (await answerCount()) >= 2, 8000)
  }

  // 2) it was transient: asking for the SAME route again shows the real screen
  const n1 = await answerCount()
  const loadsBefore = loads.length
  await say('hello')
  check('navigation-requested to the same route brings the real screen back',
    await waitFor(async () => loads.slice(loadsBefore).some((u) => /\/sync\/hello$/.test(u)) && !(await content()).includes(GENERATED), 3500))
  await waitFor(async () => (await answerCount()) > n1, 8000)

  // 3) navigation-requested navigates (mid-stream too)
  const n2 = await answerCount()
  await say('products')
  const navigated = await waitFor(async () => /products/.test(page.url()), 3500)
  check('navigation-requested navigates in the app', navigated, page.url())
  check('…mid-stream', navigated && (await answerCount()) === n2)
  await waitFor(async () => (await answerCount()) > n2, 8000)
  await waitForVbReady(page, { timeout: 15000 })

  // 4) drawer / dialog targets and the invalid YAML
  await go('/hello', ['Hola desde Mateu'])
  await say('drawer')
  check('target "drawer" opens a drawer with the generated screen and its title',
    await waitFor(async () => {
      const t = await page.locator('body').innerText().catch(() => '')
      return t.includes('Generated drawer') && t.includes('Guest') && !t.includes(GENERATED)
    }, 4000))
  await page.screenshot({ path: '/tmp/vb-chat-drawer.png' })
  await waitFor(answered, 8000)
  await go('/hello', ['Hola desde Mateu'])
  await say('dialog')
  check('target "dialog" opens a dialog with the generated screen',
    await waitFor(async () => (await page.locator('body').innerText().catch(() => '')).includes('Generated dialog'), 4000))
  await page.screenshot({ path: '/tmp/vb-chat-dialog.png' })
  await waitFor(answered, 8000)
  await go('/hello', ['Hola desde Mateu'])
  await say('bad')
  check('an invalid YAML shows the backend\'s red text',
    await waitFor(async () => (await content()).includes('Invalid or empty YAML'), 4000))
  await waitFor(answered, 8000)

  // 5) a page that DOES subscribe (ChatGenerate @SubscribeTo render-screen → renderScreen): it takes it
  await go('/ai-screen', [])
  const before = previews.length
  await say('render')
  check('a page subscribed to render-screen runs ITS action with the detail',
    await waitFor(async () => (await content()).includes(GENERATED), 5000))
  check('…and the shell does not preview it itself', previews.length === before, `${previews.length - before} preview call(s)`)
  await waitFor(answered, 8000)

  // 6) close-requested closes the panel
  await say('close')
  check('close-requested closes the chat panel', await waitFor(async () => !(await chatOpen()), 4000))
} catch (e) {
  check('probe ran to the end', false, String(e && e.message).split('\n')[0])
} finally {
  await browser.close()
  agent.close()
}
const failed = results.filter((r) => !r).length
console.log(`\n${results.length - failed}/${results.length} checks passed`)
process.exit(failed ? 1 : 0)
