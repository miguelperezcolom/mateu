import { test, expect, Page } from '@playwright/test';

// The AI chat's events, end to end (ChatLabApp, /chat-lab). The agent is a stub answered here, in
// the browser: the app declares a RELATIVE sse url (/chat-lab-agent/stream) and the test fulfils
// the panel's POST with a scripted SSE body — so the same spec runs against every adapter.
//
//  - render-screen on a page that subscribes to NOTHING is rendered by the shell itself (the
//    built-in render target, through __preview__): in the content area, a drawer or a dialog;
//  - render-screen on a page that subscribes to it is that page's — the shell leaves it alone;
//  - navigation-requested navigates, and the next navigation brings the route's own screen back.

const sse = (...events: unknown[]) =>
  events.map((e) => `data:${typeof e === 'string' ? e : JSON.stringify(e)}\n\n`).join('');

/** Every message the panel sends gets `body` as the agent's answer; the bodies sent are kept. */
async function agent(page: Page, body: () => string) {
  const sent: Record<string, unknown>[] = [];
  await page.route('**/chat-lab-agent/stream', async (route) => {
    sent.push(JSON.parse(route.request().postData() ?? '{}'));
    await route.fulfill({ status: 200, contentType: 'text/event-stream', body: body() });
  });
  return sent;
}

async function ask(page: Page, text: string) {
  const input = page.locator('mateu-chat .msg-input');
  if (!(await input.isVisible())) await page.locator('.mateu-chat-toggle').first().click();
  await expect(input).toBeVisible();
  await input.fill(text);
  await input.press('Enter');
}

const GENERATED = 'type: VerticalLayout\ncontent:\n  - type: Text\n    text: "Generated by the agent"\n';

test.describe('AI chat events (/chat-lab)', () => {

  test('a render-screen no page subscribes to is rendered by the shell in the content area', async ({ page }) => {
    const sent = await agent(page, () => sse('Here it is.', { event: 'render-screen', detail: { yaml: GENERATED } }));
    await page.goto('/chat-lab/plain');
    await expect(page.getByRole('heading', { name: 'Plain chat page' })).toBeVisible();

    await ask(page, 'a screen please');
    await expect(page.locator('mateu-ux[data-content-view]').getByText('Generated by the agent')).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Plain chat page' })).toHaveCount(0);
    // the answer's text is shown too, and the request named the screen it was asked from
    await expect(page.locator('mateu-chat').getByText('Here it is.')).toBeVisible();
    expect(sent[0].currentRoute).toBe('/chat-lab/plain');
    expect(Array.isArray(sent[0].menuContext)).toBe(true);

    // transient: the menu entry brings the route's own screen back
    await page.locator('mateu-app').getByText('Plain', { exact: true }).first().click();
    await expect(page.getByRole('heading', { name: 'Plain chat page' })).toBeVisible();
  });

  test('a render-screen can target a drawer or a dialog over the page', async ({ page }) => {
    let target = 'drawer';
    await agent(page, () => sse({ event: 'render-screen', detail: { yaml: GENERATED, target, title: 'From the agent' } }), );
    await page.goto('/chat-lab/plain');
    await expect(page.getByRole('heading', { name: 'Plain chat page' })).toBeVisible();

    await ask(page, 'in a drawer');
    const drawer = page.locator('mateu-drawer');
    await expect(drawer.getByText('Generated by the agent')).toBeVisible();
    await expect(drawer.getByText('From the agent')).toBeVisible();
    // the page is still there, under it
    await expect(page.getByRole('heading', { name: 'Plain chat page' })).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(drawer.getByText('Generated by the agent')).toHaveCount(0);

    target = 'dialog';
    await ask(page, 'in a dialog');
    await expect(page.locator('mateu-dialog').getByText('Generated by the agent')).toBeVisible();
  });

  test('invalid YAML shows the preview\'s own notice', async ({ page }) => {
    await agent(page, () => sse({ event: 'render-screen', detail: { yaml: 'type: [unclosed' } }));
    await page.goto('/chat-lab/plain');
    await expect(page.getByRole('heading', { name: 'Plain chat page' })).toBeVisible();
    await ask(page, 'broken');
    await expect(page.locator('mateu-ux[data-content-view]').getByText(/Invalid (or empty )?YAML/)).toBeVisible();
  });

  test('a page that subscribes to render-screen takes it; the shell leaves it alone', async ({ page }) => {
    await agent(page, () => sse({ event: 'render-screen', detail: { yaml: GENERATED } }));
    await page.goto('/chat-lab/subscribed');
    await expect(page.getByRole('group', { name: 'Received' })).toContainText('nothing yet');
    await ask(page, 'a screen please');
    await expect(page.getByRole('group', { name: 'Received' })).toContainText(/The page took it: \d+ chars/);
    await expect(page.getByText('Generated by the agent')).toHaveCount(0);
  });

  test('navigation-requested navigates', async ({ page }) => {
    await agent(page, () => sse('Opening it.', {
      event: 'navigation-requested',
      detail: { route: '/chat-lab/target', consumedRoute: '', actionId: '', baseUrl: '', serverSideType: '', uriPrefix: '' },
    }));
    await page.goto('/chat-lab/plain');
    await expect(page.getByRole('heading', { name: 'Plain chat page' })).toBeVisible();
    await ask(page, 'take me there');
    await expect(page.getByRole('heading', { name: 'Chat target page' })).toBeVisible();
    await expect(page).toHaveURL(/\/chat-lab\/target$/);
  });
});
