"""The ETA of a running task (``ProgressDto.eta_seconds``), estimated by the SERVER from the
``Progress`` updates it streams — the Python twin of Java's ``EtaEstimator``; the rules are the
corpus ``conformance/progress/eta.json`` (generated by ``eta.generate.mjs``) every backend runs.

Determinate only (``fraction``, else ``done/total``): an exponentially smoothed rate (alpha 0.3) of
the segments that advance; an estimate only after 2 rate updates and 2 s since the first sample,
and while 0 < p < 1; going backwards starts over. Never for an indeterminate or finished task
(EXPERIMENTAL)."""

from __future__ import annotations

import math

ALPHA = 0.3
MIN_RATE_UPDATES = 2
MIN_ELAPSED_MS = 2000


class EtaEstimator:
    """One task's estimator: feed it each update in order (``observe``), it answers the seconds left
    or None."""

    def __init__(self) -> None:
        self._first: tuple[float, float] | None = None
        self._prev: tuple[float, float] | None = None
        self._ema: float | None = None
        self._updates = 0

    def observe(
        self,
        now_ms: float,
        fraction: float | None = None,
        done: int | None = None,
        total: int | None = None,
        state: str | None = "running",
    ) -> int | None:
        if state is not None and state != "running":
            return None
        if fraction is not None:
            p = float(fraction)
        elif total is not None and total > 0:
            p = float(done or 0) / float(total)
        else:
            return None
        if not math.isfinite(p):
            return None
        t = float(now_ms)
        prev = self._prev
        if prev is None or p < prev[1] or t < prev[0]:
            self._first = (t, p)
            self._prev = (t, p)
            self._ema = None
            self._updates = 0
            return None
        if p > prev[1] and t > prev[0]:
            rate = (p - prev[1]) / (t - prev[0])
            self._ema = rate if self._ema is None else ALPHA * rate + (1 - ALPHA) * self._ema
            self._updates += 1
            self._prev = (t, p)
        ema = self._ema
        first = self._first
        if (
            self._updates < MIN_RATE_UPDATES
            or first is None
            or t - first[0] < MIN_ELAPSED_MS
            or ema is None
            or not ema > 0
            or not 0 < p < 1
        ):
            return None
        # a hair under an exact second is that second (floating point noise must not add one)
        return math.ceil((1 - p) / ema / 1000 - 1e-6)

    def observe_progress(self, now_ms: float, progress) -> int | None:
        """``observe`` for a ``ProgressDto``."""
        return self.observe(now_ms, progress.fraction, progress.done, progress.total, progress.state)
