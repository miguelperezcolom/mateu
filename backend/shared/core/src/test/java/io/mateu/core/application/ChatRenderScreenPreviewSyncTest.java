package io.mateu.core.application;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import io.mateu.core.testutil.SpecsDir;
import io.mateu.core.testutil.TestIdentities;
import io.mateu.core.testutil.TestMateu;
import io.mateu.dtos.RunActionRqDto;
import io.mateu.uidl.annotations.EyesOnly;
import io.mateu.uidl.annotations.UI;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Map;
import java.util.concurrent.atomic.AtomicInteger;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * The chat's BUILT-IN render target: when the agent sends {@code render-screen} and no page on
 * screen subscribes to it, every renderer's shell posts the definition to the reserved {@code
 * __preview__} action from whatever page the user is on. That makes {@code __preview__} callable
 * from ANY page, so these pin that it cannot be used to see more than the caller may:
 *
 * <ul>
 *   <li>it renders only the definition it is given: no view model is created or bound, so the class
 *       behind the current route — even one the caller may not open — never runs;
 *   <li>it still goes through the route guard: on a route whose {@code access:} refuses the caller
 *       it answers 403, like any other request to that route;
 *   <li>a {@code serverSideType} it is sent still goes through the wire-type policy;
 *   <li>wire-only types (a {@code ServerSideComponent} naming a class) are not authorable, so a
 *       definition cannot smuggle in an island bound to a view model.
 * </ul>
 */
class ChatRenderScreenPreviewSyncTest {

  private static final ObjectMapper JSON =
      new ObjectMapper()
          .registerModule(new JavaTimeModule())
          .disable(SerializationFeature.FAIL_ON_EMPTY_BEANS);

  static final AtomicInteger CONSTRUCTED = new AtomicInteger();

  @UI("/supervisor-only-preview")
  @EyesOnly(roles = "supervisor")
  public static class SupervisorScreen {
    public String secret = "only for supervisors";

    public SupervisorScreen() {
      CONSTRUCTED.incrementAndGet();
    }
  }

  private static final String GENERATED =
      "type: VerticalLayout\ncontent:\n  - type: Text\n    text: \"Generated by the agent\"\n";

  private static RunActionRqDto preview(String route, String yaml) {
    return RunActionRqDto.builder()
        .route(route)
        .consumedRoute("")
        .actionId("__preview__")
        .initiatorComponentId("content")
        .componentState(Map.of())
        .parameters(Map.of("_yaml", yaml))
        .build();
  }

  private static boolean refused(Throwable error) {
    var names = new ArrayList<String>();
    for (Throwable t = error; t != null; t = t.getCause()) {
      names.add(t.getClass().getSimpleName());
    }
    return names.contains("MateuForbiddenException");
  }

  @Test
  void onARouteTheCallerMayNotOpenItRendersWhatItIsGivenAndNothingOfTheRoute() {
    try (var mateu = TestMateu.withUis(SupervisorScreen.class)) {
      CONSTRUCTED.set(0);
      var wire =
          JSON.valueToTree(
                  mateu.run(
                      preview("/supervisor-only-preview", GENERATED),
                      TestIdentities.headersWithRoles("housekeeping")))
              .toString();
      assertThat(wire).contains("Generated by the agent").doesNotContain("only for supervisors");
      assertThat(CONSTRUCTED.get()).isZero();
    }
  }

  @Test
  void aServerSideTypeItIsSentStillGoesThroughTheWireTypePolicy() {
    try (var mateu = TestMateu.withUis(SupervisorScreen.class)) {
      var rq =
          RunActionRqDto.builder()
              .route("/supervisor-only-preview")
              .consumedRoute("")
              .actionId("__preview__")
              .initiatorComponentId("content")
              .serverSideType(SupervisorScreen.class.getName())
              .componentState(Map.of())
              .parameters(Map.of("_yaml", GENERATED))
              .build();
      Throwable error = null;
      try {
        mateu.run(rq, TestIdentities.headersWithRoles("housekeeping"));
      } catch (Throwable t) {
        error = t;
      }
      assertThat(error).isNotNull();
      assertThat(refused(error)).isTrue();
    }
  }

  @Test
  void aWireOnlyIslandBoundToAViewModelIsNotAuthorable() {
    try (var mateu = TestMateu.withUis(SupervisorScreen.class)) {
      CONSTRUCTED.set(0);
      var yaml =
          "type: ServerSideComponent\nserverSideType: "
              + SupervisorScreen.class.getName()
              + "\nroute: /supervisor-only-preview\n";
      var wire = JSON.valueToTree(mateu.run(preview("", yaml))).toString();
      assertThat(wire).contains("Invalid or empty YAML").doesNotContain("only for supervisors");
      assertThat(CONSTRUCTED.get()).isZero();
    }
  }

  @TempDir Path dir;

  @Test
  void onARouteWhoseAccessRefusesTheCallerItIsRefusedLikeAnyOtherRequest() {
    var root =
        SpecsDir.write(
            dir,
            Map.of(
                "routes.yaml",
                "type: Routes\nroutes:\n  - route: admin/users\n    layout: plain.yaml\n"
                    + "    access: {roles: [admin]}\n  - route: plain\n    layout: plain.yaml\n",
                "plain.yaml",
                "layout:\n  type: Text\n  text: \"Plain page\"\n"));
    Throwable refusal =
        SpecsDir.over(
            root,
            cl -> {
              try (var mateu = TestMateu.withUis()) {
                try {
                  mateu.run(preview("admin/users", GENERATED), Map.of());
                  return null;
                } catch (Throwable t) {
                  return t;
                }
              }
            });
    assertThat(refusal).isNotNull();
    assertThat(refused(refusal)).isTrue();
    String allowed =
        SpecsDir.over(
            root,
            cl -> {
              try (var mateu = TestMateu.withUis()) {
                return JSON.valueToTree(mateu.run(preview("plain", GENERATED), Map.of()))
                    .toString();
              }
            });
    assertThat(allowed).contains("Generated by the agent");
  }
}
