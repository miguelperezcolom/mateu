package io.mateu;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;
import org.springframework.context.annotation.Import;

/**
 * Mounts the screens of a third-party Mateu UI module (a jar whose {@code @UI} classes someone else
 * wrote, e.g. a workflow engine's console) in this application, in-process.
 *
 * <p>Mateu registers only its OWN beans ({@link MateuAutoConfiguration}); the beans of any other
 * package, even one under {@code io.mateu.*}, are the application's call. A UI module's controllers
 * and route resolvers (generated by the annotation processor into the package of each {@code @UI}
 * class) and its supporting beans live in its own package, so the application names that package
 * here:
 *
 * <pre>{@code
 * @SpringBootApplication
 * @EnableMateuUiModules("io.mateu.workflow.infra.in.ui")
 * public class MyApp {}
 * }</pre>
 *
 * <p>Equivalent, without code: {@code mateu.ui.modules=io.mateu.workflow.infra.in.ui} (a
 * comma-separated list, or {@code MATEU_UI_MODULES}). Both scan exactly like a
 * {@code @ComponentScan} of those packages ({@code @Component}s, {@code @Named} beans,
 * {@code @Configuration} classes), and the scanned beans are reported once at startup.
 *
 * @see MateuUiModulesRegistrar
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
@Import(MateuUiModulesRegistrar.class)
public @interface EnableMateuUiModules {

  /** The base packages of the UI modules to mount (alias of {@link #basePackages()}). */
  String[] value() default {};

  /** The base packages of the UI modules to mount. */
  String[] basePackages() default {};

  /** Type-safe alternative: the package of each class given is mounted. */
  Class<?>[] basePackageClasses() default {};
}
