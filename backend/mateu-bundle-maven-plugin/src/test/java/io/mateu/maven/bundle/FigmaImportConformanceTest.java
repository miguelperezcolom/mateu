package io.mateu.maven.bundle;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.junit.Assert.assertThrows;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import org.apache.maven.plugin.MojoFailureException;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

/**
 * The Figma import rules against the shared corpus {@code conformance/client/figma-import.json}
 * (generated by the VS Code extension's figmaImport.ts, the reference; also run by the IntelliJ
 * plugin), plus the token lookup and the errors raised before node runs.
 */
public class FigmaImportConformanceTest {

  static final Path CORPUS = Path.of("../../conformance/client/figma-import.json");

  @Rule public TemporaryFolder tmp = new TemporaryFolder();

  private static JsonNode corpus() throws Exception {
    return new ObjectMapper().readTree(Files.readString(CORPUS));
  }

  @Test
  public void fileKeys() throws Exception {
    for (var c : corpus().path("fileKeys")) {
      var input = c.path("input").asText();
      if (c.path("error").asBoolean())
        assertThatThrownBy(() -> FigmaImport.fileKey(input))
            .as(input)
            .isInstanceOf(IllegalArgumentException.class);
      else assertThat(FigmaImport.fileKey(input)).as(input).isEqualTo(c.path("key").asText());
    }
  }

  @Test
  public void routeAppends() throws Exception {
    for (var c : corpus().path("routeAppends")) {
      var got =
          FigmaImport.appendImportedRoute(
              c.path("text").asText(), c.path("route").asText(), c.path("layout").asText());
      if (c.path("expected").isNull()) assertThat(got).as(c.path("name").asText()).isEmpty();
      else assertThat(got).as(c.path("name").asText()).contains(c.path("expected").asText());
    }
  }

  @Test
  public void pageRoutesAndRoutesFiles() throws Exception {
    for (var c : corpus().path("pageRoutes"))
      assertThat(FigmaImport.routeOfPage(c.path("path").asText()))
          .isEqualTo(c.path("route").asText());
    for (var c : corpus().path("routesFiles")) {
      var files = new ArrayList<String>();
      c.path("files").forEach(f -> files.add(f.asText()));
      var chosen = FigmaImport.routesFileFor(files);
      if (c.path("chosen").isNull()) assertThat(chosen).isEmpty();
      else assertThat(chosen).contains(c.path("chosen").asText());
    }
  }

  private FigmaMojo mojo(Map<String, Object> params, Map<String, String> env, Path home)
      throws Exception {
    var mojo = new FigmaMojo();
    Mojos.set(mojo, "out", tmp.newFolder("specs").getAbsoluteFile());
    Mojos.set(mojo, "api", "https://api.figma.com");
    mojo.environment = new HashMap<>(env);
    mojo.home = home;
    for (var p : params.entrySet()) Mojos.set(mojo, p.getKey(), p.getValue());
    return mojo;
  }

  @Test
  public void withoutATokenItSaysHowToCreateOne() throws Exception {
    var home = tmp.newFolder("home").toPath();
    var e =
        assertThrows(
            MojoFailureException.class,
            () -> mojo(Map.of("file", "AbCdEf123456XyZ"), Map.of(), home).execute());
    assertThat(e.getMessage()).contains("No Figma token").contains("File content: Read only");
  }

  @Test
  public void aBadUrlIsRefusedBeforeAnythingRuns() throws Exception {
    var home = tmp.newFolder("home").toPath();
    var e =
        assertThrows(
            MojoFailureException.class,
            () ->
                mojo(Map.of("file", "https://example.com/x"), Map.of("FIGMA_TOKEN", "t"), home)
                    .execute());
    assertThat(e.getMessage()).contains("Not a Figma file URL or key");
  }

  @Test
  public void neitherAFileNorAPayloadIsAnError() throws Exception {
    var home = tmp.newFolder("home").toPath();
    var e =
        assertThrows(MojoFailureException.class, () -> mojo(Map.of(), Map.of(), home).execute());
    assertThat(e.getMessage()).contains("-Dfigma.file=");
  }

  @Test
  public void tokenLookupOrder() throws Exception {
    var home = tmp.newFolder("home").toPath();
    assertThat(FigmaImport.token(Map.of("FIGMA_TOKEN", " a "), home)).contains("a");
    assertThat(FigmaImport.token(Map.of(), home)).isEmpty();
    Files.createDirectories(home.resolve(".config/mateu"));
    Files.writeString(home.resolve(".config/mateu/figma-token"), "c");
    assertThat(FigmaImport.token(Map.of(), home)).contains("c");
    Files.createDirectories(home.resolve(".mateu-secrets"));
    Files.writeString(home.resolve(".mateu-secrets/figma-token"), "b");
    assertThat(FigmaImport.token(Map.of(), home)).contains("b");
    assertThat(FigmaImport.token(Map.of("FIGMA_TOKEN", ""), home)).contains("b");
  }

  @Test
  public void nodeVersionsAndCandidates() {
    assertThat(
            List.of(
                FigmaImport.nodeMajor("v22.1.0").orElse(0), FigmaImport.nodeMajor("x").orElse(-1)))
        .containsExactly(22, -1);
    assertThat(FigmaImport.nodeCandidates("/opt/n/node", Map.of("PATH", "/a"), Path.of("/h")))
        .containsExactly(Path.of("/opt/n/node"));
    assertThat(
            FigmaImport.nodeCandidates(null, Map.of("PATH", "/a"), Path.of("/h")).get(0).toString())
        .startsWith("/a");
  }

  @Test
  public void routesFilesAndSpecsRoot() {
    assertThat(FigmaImport.isRoutesFile("type: Routes\nroutes: []\n")).isTrue();
    assertThat(FigmaImport.isRoutesFile("type: Form\n")).isFalse();
    assertThat(FigmaImport.isRoutesFile(": : [")).isFalse();
    assertThat(FigmaImport.specsRoot(Path.of("/x/specs/ui/sub"))).isEqualTo(Path.of("/x/specs/ui"));
    assertThat(FigmaImport.specsRoot(Path.of("/x/specs/ui"))).isEqualTo(Path.of("/x/specs/ui"));
    assertThat(
            FigmaImport.appendListItem(
                "routes: [{route: a}]\n", "routes", List.of(List.of("route", "b"))))
        .isEqualTo("routes: [{route: a}, {route: b}]\n");
    assertThatThrownBy(
            () ->
                FigmaImport.appendListItem(
                    "routes: nope\n", "routes", List.of(List.of("route", "b"))))
        .isInstanceOf(IllegalArgumentException.class);
  }
}
