// Generates poc/vendor/bundleResolver.mjs: the web renderers' static-bundle resolver and YAML
// expander (libs/mateu/src/mateu/ui/infra/http/bundleResolver.ts and its import closure — the
// expander, the action/component/field-type catalogues, the i18n helpers) as ONE self-contained
// module this core can include. It is the same closure the React Native app imports as it is; here
// it is packaged because the VB bridge is a single AMD file with no TypeScript and no bundler.
//
// No dependency: Node's own type stripping (module.stripTypeScriptTypes, Node 23.2+; CI runs 24)
// removes the types, and each file becomes a function over an `exports` object (getters, so the
// expander ⇄ action catalogue cycle resolves like ES live bindings for hoisted functions). Only
// RELATIVE runtime imports are allowed — anything else fails the generation, loudly: the closure
// must stay platform-neutral (the same rule mateuLib.ts enforces for React Native).
//
//   node poc/make-expander.mjs            writes the file (npm run bridge runs it first)
//   node poc/make-expander.mjs --check    exits 1 if the committed file is stale (test-expander.mjs)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import { stripTypeScriptTypes } from 'node:module'

const here = dirname(fileURLToPath(import.meta.url))
export const INFRA = resolve(here, '../../../libs/mateu/src/mateu/ui/infra')
export const OUT = join(here, 'vendor', 'bundleResolver.mjs')
// the entry points: what the static-remote path needs (transport.mjs staticRemoteLoad)
const ENTRIES = ['http/bundleResolver.ts', 'i18n/translations.ts']

const idOf = (file) => relative(INFRA, file).split('\\').join('/')

function transform(file, code, deps) {
  const exported = []
  // imports: `import { a, b as c } from './x.ts'` (one or several lines) → a destructuring require
  let out = code.replace(/^import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?/gm, (whole, names, spec) => {
    if (!spec.startsWith('.')) throw new Error(`${idOf(file)}: non-relative runtime import '${spec}' — the closure must stay platform-neutral`)
    const target = resolve(dirname(file), spec.endsWith('.ts') ? spec : spec + '.ts')
    deps.push(target)
    const bindings = names.split(',').map((n) => n.trim()).filter(Boolean).map((n) => {
      const m = /^(\w+)(?:\s+as\s+(\w+))?$/.exec(n)
      if (!m) throw new Error(`${idOf(file)}: unsupported import binding '${n}'`)
      return m[2] ? `${m[1]}: ${m[2]}` : m[1]
    })
    if (!bindings.length) return ''
    return `const { ${bindings.join(', ')} } = __mateuRequire(${JSON.stringify(idOf(target))});`
  })
  const leftover = /^\s*import\s[^\n]*/m.exec(out)
  if (leftover && leftover[0].trim()) throw new Error(`${idOf(file)}: unsupported import form: ${leftover[0].trim()}`)
  // exports: `export const|let|function|async function|class NAME`
  out = out.replace(/^export\s+((?:async\s+)?function\s*\*?\s*|const\s+|let\s+|class\s+)([A-Za-z_$][\w$]*)/gm, (whole, kind, name) => {
    exported.push(name)
    return kind + name
  })
  const left = /^\s*export\s[^\n]*/m.exec(out)
  if (left && left[0].trim()) throw new Error(`${idOf(file)}: unsupported export form: ${left[0].trim()}`)
  const getters = exported.map((n) => `Object.defineProperty(exports, ${JSON.stringify(n)}, { enumerable: true, get: () => ${n} });`)
  return [...getters, out].join('\n')
}

export function generate() {
  const order = []
  const seen = new Set()
  const hash = createHash('sha256')
  const visit = (file) => {
    if (seen.has(file)) return
    seen.add(file)
    const source = readFileSync(file, 'utf8')
    hash.update(idOf(file) + '\0' + source + '\0')
    const deps = []
    const body = transform(file, stripTypeScriptTypes(source), deps)
    order.push({ id: idOf(file), body })
    deps.forEach(visit)
  }
  ENTRIES.forEach((e) => visit(resolve(INFRA, e)))
  const indent = (text) => text.split('\n').map((l) => (l.trim() ? '    ' + l.replace(/\s+$/, '') : '')).join('\n')
  const modules = order.map(({ id, body }) =>
    `  // ── ${id} ──\n  __defs[${JSON.stringify(id)}] = function (exports, __mateuRequire) {\n${indent(body)}\n  }`).join('\n\n')
  return `// GENERATED by poc/make-expander.mjs from libs/mateu/src/mateu/ui/infra — DO NOT EDIT.
// ${order.map((m) => m.id).join(', ')}
// source sha256 ${hash.digest('hex')}
// The web renderers' static-bundle resolver + YAML expander, for a static remote (transport.mjs).
export const mateuBundleResolver = (function () {
  'use strict'
  const __defs = {}
  const __cache = {}
  function __mateuRequire(id) {
    if (__cache[id]) return __cache[id]
    const define = __defs[id]
    if (!define) throw new Error('mateu: the bundled resolver has no module ' + id)
    const exports = {}
    __cache[id] = exports
    define(exports, __mateuRequire)
    return exports
  }

${modules}

  const resolver = __mateuRequire('http/bundleResolver.ts')
  const i18n = __mateuRequire('i18n/translations.ts')
  return Object.freeze({
    parseBundleManifest: resolver.parseBundleManifest,
    isBundleManifest: resolver.isBundleManifest,
    resolveLoad: resolver.resolveLoad,
    rootIncrement: resolver.rootIncrement,
    appShellOf: resolver.appShellOf,
    toSyncPath: resolver.toSyncPath,
    queryOf: resolver.queryOf,
    pickLocale: i18n.pickLocale,
    translateDeep: i18n.translateDeep,
    mentionsI18n: i18n.mentionsI18n,
    browserLocales: i18n.browserLocales,
  })
})()
`
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const text = generate()
  if (process.argv.includes('--check')) {
    let committed = ''
    try { committed = readFileSync(OUT, 'utf8') } catch (e) { /* missing */ }
    if (committed !== text) {
      console.error('make-expander: poc/vendor/bundleResolver.mjs is stale — run `npm run bridge`')
      process.exit(1)
    }
    console.log('make-expander: up to date')
  } else {
    mkdirSync(dirname(OUT), { recursive: true })
    writeFileSync(OUT, text)
    console.log('Escrito ' + OUT + ' (' + text.length + ' bytes)')
  }
}
