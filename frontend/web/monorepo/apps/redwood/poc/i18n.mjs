/** The languages the renderer speaks in full (every key): the web chrome's set. */
export const FULL_LANGUAGES = ['en', 'es', 'fr', 'de', 'pt', 'it']

let explicitLanguage = ''

/** Pin the chrome language (e.g. from the app); '' goes back to the page's/browser's. */
export function setChromeLanguage(lang) { explicitLanguage = lang ? String(lang) : '' }

/** The base language code of the chrome ('en', 'es'…): explicit > <html lang> > browser > 'en'. */
export function chromeLanguage(lang) {
  const raw = lang || explicitLanguage
    || (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang)
    || (typeof navigator !== 'undefined' && navigator.language) || 'en'
  return String(raw).toLowerCase().split(/[-_]/)[0] || 'en'
}

/** A chrome text in `lang` (or the interface's language), `{name}` placeholders filled from vars. */
export function chromeText(key, vars, lang) {
  const language = chromeLanguage(lang)
  const dict = CHROME_TEXTS[language] || {}
  let text = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : CHROME_TEXTS.en[key]
  if (text == null) return key
  if (vars) text = text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])))
  return text
}

/** Every chrome text in `lang`, English filling the gaps (what the VB translation bundle carries). */
export function chromeTextsOf(lang) {
  return { ...CHROME_TEXTS.en, ...(CHROME_TEXTS[chromeLanguage(lang)] || {}) }
}

/** A running task's ETA in words (ProgressDto.etaSeconds, the server's estimate), or '' when there
 *  is none — never a guess. The rule of conformance/client/eta-format.json (round half up). */
export function etaTextOf(etaSeconds, lang) {
  if (typeof etaSeconds !== 'number' || !isFinite(etaSeconds) || etaSeconds <= 0) return ''
  if (etaSeconds < 60) return chromeText('taskEtaUnderMinute', null, lang)
  const minutes = Math.max(1, Math.floor(etaSeconds / 60 + 0.5))
  if (etaSeconds < 3600 && minutes < 60) return chromeText('taskEtaMinutes', { n: minutes }, lang)
  return chromeText('taskEtaHours', { n: Math.max(1, Math.floor(etaSeconds / 3600 + 0.5)) }, lang)
}

// ── money ─────────────────────────────────────────────────────────────────────────────────────
// The rule the web renderers follow (libs/mateu moneyFormat): an Amount ({value, currency, locale})
// is written in ITS locale and currency; a bare number declared money gets two decimals grouped the
// way the UI's locale groups them — the app's (<html lang> / explicit), else the browser's. It used to
// be hard-wired to de-DE, so an English app read "1.234,50".

/** The UI's full locale tag (explicit > <html lang> > browser > 'en'), for number formatting. */
export function uiLocale() {
  return explicitLanguage
    || (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang)
    || (typeof navigator !== 'undefined' && navigator.language) || 'en'
}

// ── dates ─────────────────────────────────────────────────────────────────────────────────────
// The date fields (oj-input-date / oj-input-date-time: forms, drawers, the row editor, a date
// range's ends, the listing's range filters) carry a converter of their OWN in the UI's locale,
// the rule the Vaadin renderer follows (apps/vaadin dateLocale.ts, #1004). Without one, JET's
// default converter writes and reads dates in whatever locale JET resolved while booting, and a
// Spanish interface could show a typed 15/2/2041 back as 2/15/2041 (and read 5/2 as May 2nd).

/** The locale dates are written and read in: the UI's (uiLocale), refined by the browser's when
 *  that one is the same language with a region (`es` + `es-MX`), canonical; 'en-US' when unusable. */
export function dateLocale() {
  const ui = String(uiLocale() || '')
  const browser = (typeof navigator !== 'undefined' && navigator.language) || ''
  let locale = ui || browser || 'en-US'
  if (ui && browser && browser.toLowerCase().startsWith(ui.toLowerCase() + '-')) locale = browser
  try {
    return Intl.getCanonicalLocales(locale.replace(/_/g, '-'))[0] || 'en-US'
  } catch (e) {
    return 'en-US'
  }
}

/** The options of a date field's JET IntlDateTimeConverter: numeric day, month and four-digit
 *  year in the locale's order (15/2/2041 in es, 2/15/2041 in en-US); `dateTime` adds the time. */
export function dateConverterOptions(kind, locale) {
  const options = { locale: locale || dateLocale(), year: 'numeric', month: 'numeric', day: 'numeric' }
  return kind === 'dateTime' ? { ...options, hour: '2-digit', minute: '2-digit' } : options
}

// A listing cell of a date / dateTime / time column: the row carries ISO text ("2026-11-05",
// "2026-11-05T10:15:30.000Z", "10:15:30"); it is written in the UI's locale with the web date
// fields' rule (apps/vaadin dateLocale.ts dateFormatSpec / formatDateParts): the locale's order,
// separator (. / - else /) and padding, the year always in four digits; a time as the locale's
// hour:minute. The ISO components are read LITERALLY — never shifted to another time zone.
const dateSpecs = new Map()

/** How `locale` writes a numeric date: {order, separator, padDay, padMonth} (en-US when unusable). */
export function dateFormatSpecOf(locale) {
  const key = String(locale || '')
  if (dateSpecs.has(key)) return dateSpecs.get(key)
  let spec = { order: ['month', 'day', 'year'], separator: '/', padDay: false, padMonth: false }
  try {
    const parts = new Intl.DateTimeFormat(key || undefined, { year: 'numeric', month: 'numeric', day: 'numeric', timeZone: 'UTC' })
      .formatToParts(new Date(Date.UTC(2027, 0, 5)))
    const order = parts.map((p) => p.type).filter((t) => t === 'day' || t === 'month' || t === 'year')
    if (order.length === 3 && new Set(order).size === 3) {
      const literal = ((parts.find((p) => p.type === 'literal') || {}).value || '').trim()
      spec = {
        order,
        separator: /^[./-]$/.test(literal) ? literal : '/',
        padDay: ((parts.find((p) => p.type === 'day') || {}).value || '').length > 1,
        padMonth: ((parts.find((p) => p.type === 'month') || {}).value || '').length > 1,
      }
    }
  } catch (e) {
    // an unknown locale keeps the en-US spec
  }
  dateSpecs.set(key, spec)
  return spec
}

const padTo = (n, width) => String(n).padStart(width, '0')
const ISO_DATE = /^(\d{4})-(\d{2})-(\d{2})/
const ISO_TIME = /^(\d{2}):(\d{2})(?::(\d{2})(?:\.\d+)?)?/

function dateWritten(year, month, day, locale) {
  const spec = dateFormatSpecOf(locale)
  return spec.order.map((part) => (part === 'year' ? padTo(year, 4)
    : part === 'month' ? padTo(month, spec.padMonth ? 2 : 1)
      : padTo(day, spec.padDay ? 2 : 1))).join(spec.separator)
}

function timeWritten(hour, minute, locale) {
  try {
    return new Intl.DateTimeFormat(locale || undefined, { hour: '2-digit', minute: '2-digit', timeZone: 'UTC' })
      .format(new Date(Date.UTC(2027, 0, 5, hour, minute)))
  } catch (e) {
    return padTo(hour, 2) + ':' + padTo(minute, 2)
  }
}

/** A temporal value as `dataType` (date | dateTime | time) reads in `locale` (default: the date
 *  locale); anything that is not that ISO text comes back as it is. */
export function temporalText(value, dataType, locale) {
  if (typeof value !== 'string') return value
  const loc = locale || dateLocale()
  const text = value.trim()
  if (dataType === 'time') {
    const t = ISO_TIME.exec(text)
    return t && Number(t[1]) < 24 && Number(t[2]) < 60 ? timeWritten(Number(t[1]), Number(t[2]), loc) : value
  }
  if (dataType !== 'date' && dataType !== 'dateTime') return value
  const d = ISO_DATE.exec(text)
  if (!d || Number(d[2]) < 1 || Number(d[2]) > 12 || Number(d[3]) < 1 || Number(d[3]) > 31) return value
  const date = dateWritten(Number(d[1]), Number(d[2]), Number(d[3]), loc)
  if (dataType === 'date') return date
  const rest = text.slice(d[0].length)
  if (!rest) return date
  const t = /^[T ]/.test(rest) ? ISO_TIME.exec(rest.slice(1)) : null
  return t && Number(t[1]) < 24 && Number(t[2]) < 60 ? date + ' ' + timeWritten(Number(t[1]), Number(t[2]), loc) : value
}

function intl(locale, options) {
  try { return new Intl.NumberFormat(locale, options) } catch (e) {
    try { return new Intl.NumberFormat(String(locale || '').replace(/_/g, '-'), options) } catch (e2) {
      return new Intl.NumberFormat('en', options)
    }
  }
}

const TWO_DECIMALS = { minimumFractionDigits: 2, maximumFractionDigits: 2 }

/** A money number with two decimals in `locale` (default: the UI's); not a finite number → ''. */
export function moneyNumberText(value, locale) {
  const n = typeof value === 'number' ? value : parseFloat(String(value))
  if (!Number.isFinite(n)) return ''
  return intl(locale || uiLocale(), TWO_DECIMALS).format(n)
}

/** Any money value as text: an Amount in its own locale/currency, a number in the UI's locale. */
export function moneyText(raw, locale) {
  const amount = raw && typeof raw === 'object' && 'value' in raw ? raw : null
  const value = amount ? amount.value : raw
  if (value === null || value === undefined || value === '') return ''
  const n = typeof value === 'number' ? value : parseFloat(String(value))
  if (Number.isNaN(n)) return String(value)
  const own = (amount && amount.locale) || locale || uiLocale()
  if (amount && amount.currency) {
    try { return new Intl.NumberFormat(own, { style: 'currency', currency: amount.currency }).format(n) } catch (e) {
      return moneyNumberText(n, own) + ' ' + amount.currency
    }
  }
  return moneyNumberText(n, own)
}
