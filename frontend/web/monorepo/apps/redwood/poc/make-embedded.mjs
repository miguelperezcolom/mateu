// Builds the EMBEDDED mode's package: the <mateu-ui> JET Custom Component a Visual Builder developer
// imports into THEIR app (VB → Components → Import, or Component Exchange) — see embedded.mjs.
//
// Nothing of it is written twice. From the standalone VB app it takes, as they are:
//   - the content page markup (main-start-page.html — itself expanded from poc/templates) inside
//     the content frame of the shell (busy/offline/error bands, banner, toast, skeleton: the slice
//     of shell-page.html between @embedded-frame and @end-embedded-frame);
//   - the descriptors VB reads (app-flow.json, the two page JSONs): variables, listeners;
//   - the action chains, bundled into one AMD module with VB's two modules (actionChain, actions)
//     resolved to embedded.mjs's runtime;
//   - the generated bridge;
//   - app.css, scoped so it does not leak into the host page.
// The component's own code is apps/redwood/embedded/mateu-ui (component.json, loader.js, the
// viewModel). Out: build/embedded/mateu-ui/ and build/embedded/mateu-ui-<version>.zip.
//
// Nothing from static.oracle.com goes in: JET, oj-sp and oj-c are the HOST's (NOTICE.md).
// Usage: node make-embedded.mjs        (npm run build:embedded; npm run build runs it)

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { deflateRawSync } from 'node:zlib'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const webApp = join(root, 'webApps', 'vbredwoodapp')

/** The shell chains the content page calls (navigation, the error band, the banner, the toast).
 *  The rest of the shell's chains are its chrome (menu, header, chat, Ask): the host's business. */
export const SHELL_CHAINS = [
  'onMateuNavigate', 'retryMateuAction', 'dismissMateuError', 'showMessageToast',
  'showNotificationMessage', 'closeMessageBanner', 'runMateuMenuRules',
]

/**
 * Module paths a Visual Builder runtime configures for the Spectra components (oj-sp depends on
 * the OARS packs) and a bare JET page does not. Applied by the component ONLY where the host lacks
 * them — never in a VB app, which has its own (and its own versions). URLs of Oracle's CDN, the
 * versions VB 2510 uses: bump them with the rest of the pins (README, "Pinned Oracle CDN versions").
 */
export const HOST_FALLBACK_PATHS = {
  'oj-oars': 'https://static.oracle.com/cdn/oars/packs/oj-oars/2601.0.1/min',
  'oj-oacp': 'https://static.oracle.com/cdn/oars/packs/oj-oacp/2601.0.1/min',
}

/** The only modules a chain may depend on — anything else must be thought about first. */
export const CHAIN_DEPENDENCIES = {
  'vb/action/actionChain': 'bridge.EmbeddedActionChain',
  'vb/action/actions': 'bridge.embeddedActions',
  'resources/js/mateu-bridge': 'bridge',
}

// ── the view ─────────────────────────────────────────────────────────────────────────────────

/** The content frame of the shell page: between the two markers. */
export function frameOf(shellHtml) {
  const start = shellHtml.indexOf('<!-- @embedded-frame')
  const end = shellHtml.indexOf('<!-- @end-embedded-frame -->')
  if (start < 0 || end < 0 || end < start) throw new Error('make-embedded: shell-page.html has no @embedded-frame … @end-embedded-frame')
  const afterStart = shellHtml.indexOf('-->', start) + 3
  return shellHtml.slice(afterStart, end)
}

/** The component's view: the frame, with VB's router outlet replaced by the content page. The
 *  outlet's role="main" is NOT kept: the main landmark is the host page's. */
export function embeddedViewOf(shellHtml, pageHtml) {
  const frame = frameOf(shellHtml)
  const outlet = /<oj-vb-content\b[^>]*>[\s\S]*?<\/oj-vb-content>/
  if (!outlet.test(frame)) throw new Error('make-embedded: the frame has no <oj-vb-content> outlet')
  const content = '<div class="mateu-embedded-content oj-flex-item" style="min-width:0">\n'
    + pageHtml + '\n</div>'
  const body = frame.replace(outlet, () => content)
  return '<!-- GENERATED by apps/redwood/poc/make-embedded.mjs from the standalone app\'s content page — do not edit -->\n'
    + '<div class="mateu-ui-root oj-web-applayout-content-nopad">' + body + '</div>\n'
}

/** Every custom element tag the view uses. */
export function tagsOf(html) {
  return [...new Set([...html.matchAll(/<(oj-[a-z0-9-]+)/g)].map((m) => m[1]))].sort()
}

// bindings and sub-elements JET registers itself (no loader to require)
const BUILT_IN = new Set(['oj-bind-if', 'oj-bind-for-each', 'oj-bind-text', 'oj-bind-slot', 'oj-bind-template-slot',
  'oj-bind-dom', 'oj-bind-switch', 'oj-defer', 'oj-chart-item', 'oj-chart-group', 'oj-chart-series', 'oj-gantt-row',
  'oj-gantt-task', 'oj-option', 'oj-optgroup'])

/** The modules that define the view's components: the pages' imports, plus the oj-c-* convention
 *  (oj-c-progress-bar → oj-c/progress-bar). Fails on a tag nothing defines. */
// modules VB resolves and a bare JET does not: oj-tab-bar lives in ojs/ojnavigationlist (the
// standalone page declares ojs/ojtabbar; the shell loads ojnavigationlist anyway, so it never shows)
export const MODULE_ALIASES = { 'ojs/ojtabbar': 'ojs/ojnavigationlist' }

export function componentModulesOf(html, imports) {
  const modules = new Set(['ojs/ojknockout', 'ojs/ojbinddom'])
  const missing = []
  for (const tag of tagsOf(html)) {
    if (BUILT_IN.has(tag)) continue
    const declared = imports[tag]
    if (declared) modules.add(MODULE_ALIASES[declared.path || declared] || declared.path || declared)
    else if (tag.startsWith('oj-c-')) modules.add('oj-c/' + tag.slice('oj-c-'.length))
    else missing.push(tag)
  }
  if (missing.length) throw new Error('make-embedded: no module for ' + missing.join(', ') + ' (add it to a page\'s imports)')
  // ojs/ojbutton also defines oj-menu-button and oj-buttonset-one, etc.: one require each is enough
  return [...modules].sort()
}

// ── the chains ───────────────────────────────────────────────────────────────────────────────

/** One AMD module holding every chain: each source runs with a local `define` that hands its
 *  factory the runtime's ActionChain/Actions and the bridge, and keeps what it returns. */
export function bundleChains(sources) {
  const parts = []
  for (const [name, src] of Object.entries(sources)) {
    for (const m of src.matchAll(/define\(\s*\[([^\]]*)\]/g)) {
      for (const dep of m[1].split(',').map((d) => d.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean)) {
        if (!CHAIN_DEPENDENCIES[dep]) throw new Error(`make-embedded: chain ${name} depends on ${dep}, which the embedded runtime does not provide`)
      }
    }
    parts.push(`  chains[${JSON.stringify(name)}] = (() => {
    let out;
    const define = (deps, factory) => { out = factory(...deps.map(resolve)); };
${src.replace(/^/gm, '    ').replace(/^ {4}$/gm, '')}
    return out;
  })();`)
  }
  return `/* GENERATED by apps/redwood/poc/make-embedded.mjs from the standalone app's action chains — do not edit. */
define(['./mateu-ui-bridge'], (bridge) => {
  'use strict';
  const modules = {
${Object.entries(CHAIN_DEPENDENCIES).map(([k, v]) => `    ${JSON.stringify(k)}: ${v},`).join('\n')}
  };
  const resolve = (dep) => modules[dep];
  const chains = {};
${parts.join('\n')}
  return chains;
});
`
}

// ── the style sheet ──────────────────────────────────────────────────────────────────────────

// shell chrome: the component has none of it (the host's header, navigation, chat)
const SHELL_ONLY = /oj-sp-simple-ui-shell|oj-sp-global-header|#pageContent|oj-sp-inappnav-visible|#mateuChatDrawer|mateu-chat|oj-sp-rw-chat|mateu-subheader|mateu-ask-|oj-sp-logo-global-header/

/** Splits on top-level commas (not inside :is(a, b) or [x="a,b"]). */
function splitSelectors(text) {
  const out = []
  let depth = 0
  let quote = null
  let cur = ''
  for (const ch of text) {
    if (quote) { if (ch === quote) quote = null; cur += ch; continue }
    if (ch === '"' || ch === "'") quote = ch
    else if (ch === '(' || ch === '[') depth++
    else if (ch === ')' || ch === ']') depth--
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; continue }
    cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

/** One selector, scoped: null drops it. Our own classes and ids (mateu-*) stay global — they mark
 *  only our markup, which JET may move to the popup layer (a dialog, a drawer) out of the
 *  component; anything else (a JET/Spectra override) applies only inside <mateu-ui>. */
export function scopeSelector(selector, scope = 'mateu-ui') {
  const s = selector.trim()
  if (!s) return null
  if (/^(html|body|:root)\b/.test(s)) return null
  if (SHELL_ONLY.test(s)) return null
  const first = s.split(/[\s>+~]/)[0]
  if (/\.mateu-|#mateu|\[data-mateu/.test(first)) return s
  return scope + ' ' + s
}

/** The app's style sheet for a host page: rule by rule, @media/@supports recursively, @keyframes
 *  and @font-face as they are. */
export function scopeCss(css, scope = 'mateu-ui') {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
  let i = 0
  const parseBlock = () => {
    let out = ''
    while (i < text.length) {
      const close = text.indexOf('}', i)
      const open = text.indexOf('{', i)
      if (close >= 0 && (open < 0 || close < open)) { i = close + 1; return out }
      if (open < 0) { i = text.length; return out }
      const head = text.slice(i, open).trim()
      i = open + 1
      if (/^@(media|supports|container|layer)\b/.test(head)) {
        const inner = parseBlock()
        if (inner.trim()) out += head + ' {\n' + inner + '}\n'
        continue
      }
      // a declaration block (or @keyframes/@font-face: copied whole, nested braces included)
      let depth = 1
      const start = i
      while (i < text.length && depth > 0) {
        if (text[i] === '{') depth++
        else if (text[i] === '}') depth--
        i++
      }
      const body = text.slice(start, i - 1)
      if (head.startsWith('@')) { out += head + ' {' + body + '}\n'; continue }
      const selectors = splitSelectors(head).map((sel) => scopeSelector(sel, scope)).filter(Boolean)
      if (selectors.length) out += selectors.join(',\n') + ' {' + body + '}\n'
    }
    return out
  }
  return '/* GENERATED by apps/redwood/poc/make-embedded.mjs from webApps/vbredwoodapp/resources/css/app.css (scoped to <mateu-ui>) — do not edit */\n'
    + `${scope} { display: block; position: relative; min-width: 0; }\n`
    + parseBlock()
}

// ── the zip (stored + deflated entries, no dependency) ───────────────────────────────────────

const CRC_TABLE = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  return t
})()

function crc32(buf) {
  let c = 0xffffffff
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

/** A zip of { name: Buffer|string }, deterministic (fixed timestamps, sorted names). */
export function zipOf(files) {
  const locals = []
  const centrals = []
  let offset = 0
  const DOS_TIME = 0
  const DOS_DATE = (2026 - 1980) << 9 | 1 << 5 | 1
  for (const name of Object.keys(files).sort()) {
    const data = Buffer.isBuffer(files[name]) ? files[name] : Buffer.from(files[name], 'utf8')
    const compressed = deflateRawSync(data, { level: 9 })
    const nameBuf = Buffer.from(name, 'utf8')
    const crc = crc32(data)
    const local = Buffer.alloc(30)
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6)
    local.writeUInt16LE(8, 8); local.writeUInt16LE(DOS_TIME, 10); local.writeUInt16LE(DOS_DATE, 12)
    local.writeUInt32LE(crc, 14); local.writeUInt32LE(compressed.length, 18); local.writeUInt32LE(data.length, 22)
    local.writeUInt16LE(nameBuf.length, 26); local.writeUInt16LE(0, 28)
    locals.push(local, nameBuf, compressed)
    const central = Buffer.alloc(46)
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6)
    central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(8, 10); central.writeUInt16LE(DOS_TIME, 12)
    central.writeUInt16LE(DOS_DATE, 14); central.writeUInt32LE(crc, 16); central.writeUInt32LE(compressed.length, 20)
    central.writeUInt32LE(data.length, 24); central.writeUInt16LE(nameBuf.length, 28)
    central.writeUInt32LE(offset, 42)
    centrals.push(central, nameBuf)
    offset += local.length + nameBuf.length + compressed.length
  }
  const centralSize = centrals.reduce((n, b) => n + b.length, 0)
  const end = Buffer.alloc(22)
  end.writeUInt32LE(0x06054b50, 0)
  end.writeUInt16LE(Object.keys(files).length, 8); end.writeUInt16LE(Object.keys(files).length, 10)
  end.writeUInt32LE(centralSize, 12); end.writeUInt32LE(offset, 16)
  return Buffer.concat([...locals, ...centrals, end])
}

// ── the package ──────────────────────────────────────────────────────────────────────────────

const read = (...p) => readFileSync(join(...p), 'utf8')
const json = (...p) => JSON.parse(read(...p))

/** The files of the component, by name in the package. */
export function componentFiles() {
  const pkg = json(root, 'package.json')
  const app = json(webApp, 'app-flow.json')
  const mainPage = json(webApp, 'flows', 'main', 'pages', 'main-start-page.json')
  const shellPage = json(webApp, 'pages', 'shell-page.json')
  const view = embeddedViewOf(read(webApp, 'pages', 'shell-page.html'), read(webApp, 'flows', 'main', 'pages', 'main-start-page.html'))
  const imports = {
    ...((shellPage.imports || {}).components || {}),
    ...((mainPage.imports || {}).components || {}),
  }
  const modules = componentModulesOf(view, imports)

  const chainSources = {}
  const mainChains = join(webApp, 'flows', 'main', 'pages', 'main-start-page-chains')
  for (const f of readdirSync(mainChains).filter((n) => n.endsWith('.js')).sort()) {
    chainSources[f.replace(/\.js$/, '')] = read(mainChains, f)
  }
  for (const name of SHELL_CHAINS) chainSources[name] = read(webApp, 'pages', 'shell-page-chains', name + '.js')

  const descriptors = {
    app: { variables: app.variables, constants: app.constants, events: app.events },
    // ONE page scope: the content page + the parts of the shell page the frame keeps
    pages: [
      { variables: mainPage.variables, eventListeners: mainPage.eventListeners },
      { variables: shellPage.variables, eventListeners: shellPage.eventListeners },
    ],
    requirejs: {
      paths: { ...((app.requirejs || {}).paths || {}), ...HOST_FALLBACK_PATHS },
      bundles: (app.requirejs || {}).bundles || {},
    },
    modules,
  }
  const component = read(root, 'embedded', 'mateu-ui', 'component.json').replace('@VERSION@', pkg.version)
  return {
    version: pkg.version,
    files: {
      'component.json': component,
      'loader.js': read(root, 'embedded', 'mateu-ui', 'loader.js'),
      'mateu-ui-viewModel.js': read(root, 'embedded', 'mateu-ui', 'mateu-ui-viewModel.js'),
      'mateu-ui-view.html': view,
      'mateu-ui-styles.css': scopeCss(read(webApp, 'resources', 'css', 'app.css'))
        + read(root, 'embedded', 'mateu-ui', 'mateu-ui-embedded.css'),
      'mateu-ui-bridge.js': read(webApp, 'resources', 'js', 'mateu-bridge.js'),
      'mateu-ui-chains.js': bundleChains(chainSources),
      'mateu-ui-descriptors.js': '/* GENERATED by apps/redwood/poc/make-embedded.mjs from the VB app descriptors — do not edit. */\n'
        + 'define([], () => (' + JSON.stringify(descriptors) + '));\n',
      'NOTICE.md': read(root, 'embedded', 'mateu-ui', 'NOTICE.md'),
    },
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { version, files } = componentFiles()
  const out = join(root, 'build', 'embedded')
  const dir = join(out, 'mateu-ui')
  if (existsSync(dir)) rmSync(dir, { recursive: true })
  mkdirSync(dir, { recursive: true })
  for (const [name, content] of Object.entries(files)) writeFileSync(join(dir, name), content)
  for (const f of readdirSync(out).filter((n) => n.endsWith('.zip'))) rmSync(join(out, f))
  const zip = join(out, `mateu-ui-${version}.zip`)
  writeFileSync(zip, zipOf(files))
  console.log(`make-embedded: ${Object.keys(files).length} files → ${dir}\n               ${zip}`)
}
