/** The languages Mateu's chrome speaks. A language outside this list falls back to English. */
export type ChromeLanguage = 'en' | 'es' | 'fr' | 'de' | 'pt' | 'it'

const TEXTS: Record<ChromeLanguage, Catalogue> = { en, es, fr, de, pt, it }

export type ChromeTextKey = keyof typeof en

/** The languages the catalogue has (for tests and tooling). */
export const CHROME_LANGUAGES = Object.keys(TEXTS) as ChromeLanguage[]

/** The catalogue of one language (for tests and tooling). */
export const chromeCatalogue = (lang: ChromeLanguage): Readonly<Catalogue> => TEXTS[lang]

/**
 * The chrome language for a BCP 47 tag: its primary subtag when the catalogue has it (`pt-BR` and
 * `pt-PT` → `pt`, `de-AT` → `de`, `es_419` → `es`), else English. With no tag: `<html lang>`, else
 * the browser's.
 */
export const chromeLanguage = (explicit?: string): ChromeLanguage => {
    const lang = explicit || (typeof document !== 'undefined' && document.documentElement?.lang)
        || (typeof navigator !== 'undefined' && navigator.language) || ''
    const primary = lang.trim().toLowerCase().split(/[-_]/)[0]
    return (CHROME_LANGUAGES as string[]).includes(primary) ? primary as ChromeLanguage : 'en'
}

export const chromeText = (key: ChromeTextKey, lang?: string): string => TEXTS[chromeLanguage(lang)][key]

/** {@link chromeText} with `{name}` placeholders filled from `vars`. */
export const chromeTextf = (key: ChromeTextKey, vars: Record<string, unknown>, lang?: string): string =>
    chromeText(key, lang).replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name] ?? '') : m))

/**
 * Sets the page language (`<html lang>`): the server's when it says one (`AppDto.locale`, the app's
 * Translator), else — on boot, when the page declares none — the browser's. Screen readers,
 * hyphenation, spell-check and the chrome catalogue all read it. Returns the language in effect.
 */
export const applyUiLanguage = (serverLocale?: string | null): string => {
    if (typeof document === 'undefined') return serverLocale || 'en'
    const root = document.documentElement
    if (serverLocale && serverLocale.trim()) {
        if (root.lang !== serverLocale) root.lang = serverLocale
    } else if (!root.lang) {
        root.lang = (typeof navigator !== 'undefined' && navigator.language) || 'en'
    }
    return root.lang
}
